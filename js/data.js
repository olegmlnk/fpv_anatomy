const MISC_G = 18;
const cfg = { frame: 'truex', motors: 'm1950', props: 'p463', esc: 'e55', fc: 'f405', rx: 't', vtx: 'an1', vtxant: 'lolli', cam: 'micro', battery: 'b6s1300', power: 'cap35', gps: 'none', tilt: 30 };

function opt(slot) { return OPTS[slot].find(o => o.id === cfg[slot]); }
function camOpt() { return opt('vtx').kind === 'digital' ? OPTS.cam.find(o => o.id === 'hdcam') : opt('cam'); }
function numN(id) { return ORDER.indexOf(id) + 1; }

const fmt = (v, d = 0) => v.toLocaleString('uk-UA', { minimumFractionDigits: d, maximumFractionDigits: d });
const round5 = v => Math.round(v / 5) * 5;

/* ---------- performance estimate ---------- */
function calc() {
  const fr = opt('frame'), mo = opt('motors'), pr = opt('props'), es = opt('esc'), fc = opt('fc'), rx = opt('rx'),
    vt = opt('vtx'), va = opt('vtxant'), ba = opt('battery'), pw = opt('power'), gp = opt('gps');
  const camG = vt.kind === 'digital' ? vt.camG : opt('cam').g;
  const parts = {
    frame: fr.g, motors: mo.g * 4, props: pr.g * 4, esc: es.g, fc: fc.g, rx: rx.g, vtx: vt.g,
    vtxant: va.g * (vt.dual ? 2 : 1), cam: camG, battery: ba.g, power: pw.g, gps: gp.g
  };
  const auw = Object.values(parts).reduce((a, b) => a + b, 0) + MISC_G;
  const cell = ba.chem === 'liion' ? 3.6 : 3.7;
  const vNom = ba.s * cell, vFull = ba.s * 4.2;
  const rpmMax = mo.kv * vFull;
  const kr = mo.kv * vNom * 0.8 / 1000;
  const thrust = pr.k * kr * kr;
  const tw = thrust * 4 / auw;
  const iMotor = pr.c * kr * kr * kr / vNom;
  const iTotal = iMotor * 4;
  const pHover = auw / pr.eff;
  const wh = ba.ah * vNom * (ba.chem === 'liion' ? 0.75 : 0.8);
  const tHover = wh / pHover * 60;
  const tAgg = tHover / 2.6;

  const warns = [];
  if (mo.kv >= 2300 && ba.s === 6) warns.push(['bad', `Мотори ${mo.kv}KV на 6S: піковий струм ≈${fmt(iMotor)} А на мотор. Перегрів моторів і ESC — для 6S беріть 1700–2000KV.`]);
  if (mo.kv <= 2000 && ba.s === 4) warns.push(['warn', `${mo.kv}KV на 4S дає мало обертів: дрон буде млявим. Для 4S типово 2300–2800KV.`]);
  if (iMotor > es.burst) warns.push(['bad', `ESC ${es.cont}A не витримає піків ≈${fmt(iMotor)} А на мотор: візьміть потужніший ESC або нижчий KV.`]);
  else if (iMotor > es.cont) warns.push(['warn', `Піки ≈${fmt(iMotor)} А на мотор вищі за тривалі ${es.cont} А ESC: короткі ривки витримає, але грітиметься.`]);
  if (ba.s > es.maxS) warns.push(['bad', `ESC розрахований максимум на ${es.maxS}S.`]);
  if (ba.maxA && iTotal > ba.maxA) warns.push(['warn', `Li-ion віддає ≈${ba.maxA} А, а на повному газі мотори просять ≈${fmt(iTotal)} А. Напруга просідатиме — тільки плавний політ.`]);
  if (!pw.cap) warns.push(['bad', 'Без конденсатора стрибки напруги від моторів можуть спалити ESC і додають шум у відео.']);
  if (tw < 4) warns.push(['warn', `Тяга/вага ${fmt(tw, 1)}:1 — замало для впевненого керування й виходу з піке.`]);
  if (vt.id === 'an25') warns.push(['warn', '2,5 Вт сильно гріється: на землі тримайте pit mode або 25 мВт, у повітрі потрібен обдув.']);
  if (va.pol === 'лінійна') warns.push(['warn', 'Лінійний диполь з круговими антенами окулярів: втрата ≈3 дБ і більше відбиттів.']);
  if (rx.ant === 'ceramic') warns.push(['info', 'Керамічна антена — для мікро-дронів: на 5″ у неї найменша дальність керування.']);
  if (rx.ant === 'div') warns.push(['info', 'Diversity: приймач обирає антену з кращим сигналом. Антени розвернуті під 90°.']);
  if (vt.kind === 'digital') warns.push(['info', 'Цифрова система йде зі своєю камерою — аналогову камеру знято.']);
  if (gp.id === 'none') warns.push(['info', 'Без GPS немає GPS Rescue та Position Hold.']);
  if (fr.id === 'deadcat') warns.push(['info', 'Deadcat: пропелери не потрапляють у кадр камери.']);
  const rank = { bad: 0, warn: 1, info: 2 };
  warns.sort((a, b) => rank[a[0]] - rank[b[0]]);

  const prof = [];
  if (ba.chem === 'liion' || rx.ant === 'imt') prof.push('Лонг-рейндж');
  if (mo.kv >= 2450 && ba.s === 4) prof.push('Рейсинг 4S');
  else if (tw >= 8 && ba.chem === 'lipo') prof.push(`Фрістайл ${ba.s}S`);
  if (vt.kind === 'digital') prof.push('HD-відео');
  if (gp.id !== 'none') prof.push('GPS Rescue');
  if (fr.id === 'deadcat') prof.push('Кінозйомка');

  return { parts, auw, vNom, vFull, rpmMax, thrust, tw, iMotor, iTotal, tHover, tAgg, warns, prof, link: rx.link, lat: vt.lat, img: vt.img };
}
